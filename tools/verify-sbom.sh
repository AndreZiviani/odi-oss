#!/usr/bin/env bash
#
# Check a release SBOM without trusting it: the structure, the licenses, the
# hashes, the dependency graph (no build tool is a runtime dependency), and
# optionally the files and the checksum list.
#
#     tools/verify-sbom.sh sbom.cdx.json [--sums SHA256SUMS] [--rootfs DIR]
#
#   --sums    the SBOM must be listed in SHA256SUMS with its own hash
#   --rootfs  an unpacked image (unsquashfs the rootfs member of the release
#             tarball): every file the SBOM lists is re-hashed there
#
# Together with `gh attestation verify sbom.cdx.json -R AndreZiviani/odi-oss`
# (docs/FLASHING.md, "Verifying a release") this is the whole check. Needs
# python3 and nothing else. test/sbom_test.sh runs it in CI, against a SBOM
# generated by tools/generate-sbom.sh and against deliberately broken ones.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
[ $# -ge 1 ] || { echo "usage: verify-sbom.sh sbom.cdx.json [--sums SHA256SUMS] [--rootfs DIR]" >&2; exit 2; }
exec python3 -I "$ROOT/tools/sbom.py" verify "$@"
